#!/usr/bin/env python3
"""Build the Cultivate Play website.

  1. Compiles src/components/*.jsx -> assets/js/*.js  (needs esbuild: `npm i -g esbuild`, or npx)
  2. Copies each page shell in src/pages/ to its output path
  3. Opens each page in a headless browser and saves the fully rendered
     content into the HTML, so search engines see real text without
     having to run JavaScript.  (needs: pip install playwright && playwright install chromium)

Run from the repository root:   python3 tools/build.py
"""
import functools, http.server, json, os, re, shutil, subprocess, sys, threading

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAGES = {  # source shell -> published file
    "src/pages/home.html": "index.html",
    "src/pages/floortime.html": "floortime/index.html",
}
CHROME = os.environ.get("CHROME_PATH")  # optional: use a specific Chromium binary


def compile_components():
    esbuild = shutil.which("esbuild")
    cmd = [esbuild] if esbuild else ["npx", "--yes", "esbuild@0.24.0"]
    comp_dir = os.path.join(ROOT, "src", "components")
    for name in sorted(os.listdir(comp_dir)):
        if not name.endswith(".jsx"):
            continue
        out = os.path.join(ROOT, "assets", "js", name[:-4] + ".js")
        subprocess.run(cmd + [
            os.path.join(comp_dir, name), "--outfile=" + out, "--format=iife",
            "--jsx=transform", "--jsx-factory=React.createElement", "--jsx-fragment=React.Fragment",
            "--target=es2017", "--minify", "--log-level=warning",
        ], check=True)
        print("compiled", name)


def serve():
    class Quiet(http.server.SimpleHTTPRequestHandler):
        def log_message(self, *a):
            pass
    handler = functools.partial(Quiet, directory=ROOT)
    srv = http.server.ThreadingHTTPServer(("127.0.0.1", 0), handler)
    threading.Thread(target=srv.serve_forever, daemon=True).start()
    return srv


def faq_schema(items):
    data = {"@context": "https://schema.org", "@type": "FAQPage", "mainEntity": [
        {"@type": "Question", "name": i["q"], "acceptedAnswer": {"@type": "Answer", "text": i["a"]}} for i in items]}
    return '<script type="application/ld+json">\n' + json.dumps(data, indent=2, ensure_ascii=False) + "\n</script>"


def prerender():
    from playwright.sync_api import sync_playwright
    srv = serve()
    base = "http://127.0.0.1:%d/" % srv.server_address[1]
    with sync_playwright() as p:
        browser = p.chromium.launch(**({"executable_path": CHROME} if CHROME else {}))
        for src, out in PAGES.items():
            shell = open(os.path.join(ROOT, src), encoding="utf-8").read()
            shell = re.sub(r"<!-- SOURCE FILE.*?-->\n", "<!-- Generated by tools/build.py from %s. Edit that file, not this one. -->\n" % src, shell)
            out_path = os.path.join(ROOT, out)
            os.makedirs(os.path.dirname(out_path) or ROOT, exist_ok=True)
            open(out_path, "w", encoding="utf-8").write(shell)
            page = browser.new_page(viewport={"width": 1280, "height": 900})
            errors = []
            page.on("pageerror", lambda e: errors.append(str(e)))
            page.goto(base + out.replace("index.html", ""), wait_until="networkidle")
            page.wait_for_function("document.querySelector('#root main') !== null", timeout=15000)
            page.wait_for_timeout(500)
            if errors:
                sys.exit("Errors on %s: %s" % (out, errors))
            html = page.evaluate("document.getElementById('root').innerHTML")
            faq = page.evaluate("window.__pageFaq || null")
            page.close()
            result = shell.replace('<div id="root"></div>', '<div id="root">' + html + "</div>", 1)
            result = result.replace("<!-- FAQ_SCHEMA -->", faq_schema(faq) if faq else "")
            open(out_path, "w", encoding="utf-8").write(result)
            text = re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", html))
            print("rendered %-22s %6d characters of text" % (out, len(text)))
        browser.close()
    srv.shutdown()


if __name__ == "__main__":
    compile_components()
    prerender()
